#!/bin/bash
# usage: ./doit.sh top   (or ./doit.sh top.sv)
# compiles every .sv in this folder, with <name> as the top module
set -e

NAME=${1%.sv}                  # strip .sv if you typed it
[ -z "$NAME" ] && { echo "usage: ./doit.sh <top module>"; exit 1; }

# attach Vbuddy to WSL (only in folders that use Vbuddy)
if [ -f vbuddy.cfg ]; then
    ~/Documents/iac/lab0-devtools/tools/attach_usb.sh
fi

# cleanup
rm -rf obj_dir
rm -f *.vcd

# run Verilator on all modules in this folder, with NAME as the top level
verilator -Wall --cc --trace *.sv --top-module ${NAME} --exe ${NAME}_tb.cpp

# build C++ project via make automatically generated by Verilator
make -j -C obj_dir/ -f V${NAME}.mk V${NAME}

# run executable simulation file
obj_dir/V${NAME}
